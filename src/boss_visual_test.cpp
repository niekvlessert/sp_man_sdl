#include "play_session.hpp"
#include "assets.hpp"
#ifdef NDEBUG
#undef NDEBUG
#endif
#include <array>
#include <cassert>
#include <iostream>

int main(int argc,char** argv) {
    if(argc!=2) return 2;
    sm::Rom rom(argv[1]);
    struct Capture {std::array<std::uint8_t,64> object;std::uint32_t stamp_hash;};
    // Original-ROM OpenMSX captures after the $3E shell's $7B65 call
    // ($A655), and after the $14 static list plus $AFD4 components ($AE73).
    // D988 was cleared at entry; hashes cover the first 32 of 48 cells/row.
    constexpr std::array<Capture,2> captures{{
    {{0x3e,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x01,0xe0,0x1e,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x03,0x83,0x04,0x78,0x02,0x14,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x01,0x00,0x02,0x02,0xf4,0xea,0x00,0x80,0x00,0x00,0x03,0x00,0x03,0x00,0x03,0x00,0x00,0x00,0x01},0x453e7483u},
    {{0x14,0x02,0x00,0x00,0x00,0x00,0x00,0x00,0x09,0x40,0x14,0x00,0x00,0x00,0x00,0x01,0x08,0x18,0x01,0x08,0x85,0x14,0xf0,0x20,0x13,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x50,0x00,0x00,0x00,0x03,0x01,0x0a,0x01,0x03,0x28,0x01,0x01,0x00,0x01,0x00,0x01,0x00,0x5e,0xea,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x01},0xba70bb6bu},
    }};
    constexpr std::array<std::uint32_t,2> palette_hashes{0x13bc948du,0xd59c7676u};
    for(unsigned i=0;i<captures.size();++i) {
        const unsigned stage=i+2u;
        sm::GameState game;game.enemies[0].raw=captures[i].object;
        auto& boss=game.enemies[0];
        sm::Stage0BackgroundStream background(rom);background.reset_stage(stage);
        background.apply_object_raster_anchor(boss.x_fixed(),boss.y_fixed(),i?0xf4u:0xffu);
        std::array<std::uint8_t,24u*32u> tiles{};
        sm::stamp_stage0_tile_objects(rom,background,game,tiles,true);
        std::uint32_t hash=2166136261u;
        for(const auto tile:tiles) hash=(hash^tile)*16777619u;
        assert(hash==captures[i].stamp_hash);
        // SDL owns these actors once: no stale coarse copies on either edge.
        tiles.fill(0u);
        sm::stamp_stage0_tile_objects(rom,background,game,tiles,false);
        for(const auto tile:tiles) assert(tile==0u);
        std::array<std::uint8_t,24> edge{};
        sm::stamp_stage0_tile_objects_right_edge(rom,background,game,edge);
        for(const auto tile:edge) assert(tile==0u);
        hash=2166136261u;
        for(const auto color:sm::decode_stage_boss_palette(rom,stage)) {
            hash=(hash^std::uint8_t(color))*16777619u;
            hash=(hash^std::uint8_t(color>>8u))*16777619u;
        }
        assert(hash==palette_hashes[i]);
    }
    // Original-ROM $B521 (stage 6, centre + shell) and stage-8 handler
    // return (state 4, shell + weak point + both secondary matrices).
    constexpr std::array<Capture,2> late{{
    {{0x7b,0x03,0x00,0x00,0x00,0x01,0x02,0x40,0x0e,0x00,0x07,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x0c,0x8c,0x14,0xa0,0x14,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x01,0x02,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x01,0x01,0x01,0x00,0xb8,0xeb,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x01},0x113c103du},
    {{0x78,0x04,0x00,0x00,0x00,0x02,0x01,0x20,0x00,0xe0,0x0c,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x0b,0x93,0x3d,0x40,0x01,0x04,0x02,0x3b,0x3d,0x00,0x00,0x00,0x00,0x01,0x01,0x00,0x50,0x00,0x15,0x00,0x00,0x03,0x00,0x2a,0x03,0x00,0x01,0x00,0x01,0x00,0xd7,0xe9,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x01},0x52c2e419u},
    }};
    for(unsigned i=0;i<late.size();++i) {
        sm::GameState game;game.enemies[0].raw=late[i].object;
        auto& boss=game.enemies[0];sm::Stage0BackgroundStream background(rom);
        background.reset_stage(i?7u:5u);
        background.apply_object_raster_anchor(boss.x_fixed(),boss.y_fixed(),i?0xf8u:0xf4u);
        std::array<std::uint8_t,24u*32u> tiles{};
        sm::stamp_stage0_tile_objects(rom,background,game,tiles,true);
        std::uint32_t hash=2166136261u;
        for(const auto tile:tiles) hash=(hash^tile)*16777619u;
        assert(hash==late[i].stamp_hash);
        if(i==1u) {
            // A direct F0FC=7 run has stale title pixels. This fixture instead
            // uses VRAM carried through the original Stage-7 boss and handoff.
            const auto assets=sm::decode_stage_video(rom,7u);
            hash=2166136261u;
            for(unsigned y=0;y<24u;++y) {
                const unsigned quarter=((7u+y)&31u)/8u;
                for(unsigned x=0;x<32u;++x) if(const auto tile=tiles[y*32u+x])
                    for(unsigned base:{0x10000u,0x12000u}) for(unsigned py=0;py<8u;++py)
                        hash=(hash^assets.vram[base+quarter*0x800u+tile*8u+py])*16777619u;
            }
            assert(hash==0x4a54283au);
        }
        sm::stamp_stage0_tile_objects(rom,background,game,tiles={},false);
        for(const auto tile:tiles) assert(tile==0u);
        std::array<std::uint8_t,24> edge{};
        sm::stamp_stage0_tile_objects_right_edge(rom,background,game,edge);
        for(const auto tile:edge) assert(tile==0u);
    }
    std::cout<<"Boss visuals PASS: original Stage 3/4/6/8 stamps, palettes and single SDL ownership\n";
}
